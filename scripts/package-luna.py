#!/usr/bin/env python3
"""Pack an already prepared Luna AirPlay payload with a YAM-owned identity.

This only stages files and invokes yam-publish pack. It never installs,
publishes, builds a receiver, or changes the legacy .yap descriptor.
"""
import argparse
import json
from pathlib import Path, PurePosixPath
import re
import shutil
import subprocess
import tomllib


def stage(payload, work_dir, package, version, platform, luna_version):
    if not re.fullmatch(r'[a-z0-9-]{1,64}/[a-z0-9-]{1,64}', package):
        raise ValueError('package must be namespace/name (lowercase letters, digits, hyphens)')
    # Luna uses the two ID components to locate pkgs/<namespace>/<name>/current.
    # A namespace prefix alone passes YAM but is insufficient for binary launch.
    plugin_id = package.replace('/', '.')
    payload = payload.resolve()
    if work_dir.resolve().is_relative_to(payload):
        raise ValueError('work directory must be outside the input payload')
    for source in payload.rglob('*'):
        if source.is_symlink() or not (source.is_dir() or source.is_file()):
            raise ValueError('payload must contain only regular files and directories: ' + str(source))
    text = (payload / 'plugin.toml').read_text()
    descriptor = tomllib.loads(text)
    if descriptor.get('launch', {}).get('kind') != 'binary':
        raise ValueError('input must be a prepared Luna binary plugin')
    if descriptor.get('dependencies'):
        raise ValueError('this recipe requires a Luna-only payload without runtime dependency aliases')
    launcher = PurePosixPath(descriptor['launch'].get('path', descriptor.get('entry', '')))
    if launcher.is_absolute() or '..' in launcher.parts or not (payload / launcher).is_file():
        raise ValueError('Luna launcher must be a file inside the prepared payload')
    for key, value in (('id', plugin_id), ('version', version)):
        text, count = re.subn(r'^' + key + r'\s*=.*$',
                              key + ' = ' + json.dumps(value), text, flags=re.M)
        if count != 1:
            raise ValueError('expected exactly one descriptor field: ' + key)
    # Parse again before writing anything; all other runtime metadata is retained.
    rewritten = tomllib.loads(text)
    if rewritten != {**descriptor, 'id': plugin_id, 'version': version}:
        raise ValueError('rewriting identity must preserve all other runtime metadata')
    work_dir.mkdir(parents=True, exist_ok=False)
    target = work_dir / 'payload'
    # Preserve executable bits without following links if an input changes.
    shutil.copytree(payload, target, symlinks=True)
    (target / 'plugin.toml').write_text(text)
    manifest = {
        'name': package,
        'version': version,
        'license': 'Mixed; see bundled LICENSES/ and third_party/licenses/',
        'description': 'AirPlay receiver hosted by Luna',
        'homepage': 'https://github.com/Yandex-Station-Universal-Repo/Station-airplay',
        'targets': [platform],
        'depends': ['yam/luna >=' + luna_version],
        'replaces': ['station/airplay'],
        'files': {'share/luna/plugins/' + plugin_id + '/': 'payload/'},
    }
    # JSON is valid YAML; MANIFEST.yaml and hashes are generated by YAM itself.
    (work_dir / 'yam.yaml').write_text(json.dumps(manifest, indent=2) + '\n')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--payload', required=True, type=Path,
                   help='Prepared Luna tree with plugin.toml, launcher, runtime and licenses')
    p.add_argument('--package', required=True, help='Owned YAM namespace/name, e.g. airplay/airplay-luna')
    p.add_argument('--version', required=True, help='New package SemVer; validated by yam-publish')
    p.add_argument('--platform', required=True, help='YAM target, e.g. cucumber for Station Midi')
    p.add_argument('--luna-version', required=True, help='Minimum Luna version required by this payload')
    p.add_argument('--work-dir', required=True, type=Path, help='Fresh staging directory')
    p.add_argument('--publisher', required=True, type=Path, help='Official yam-publish executable')
    p.add_argument('--profiles', required=True, type=Path, help='YAM platform profiles directory')
    p.add_argument('--output', required=True, type=Path)
    a = p.parse_args()
    if a.output.exists():
        p.error('output already exists; choose another path')
    try:
        stage(a.payload, a.work_dir, a.package, a.version, a.platform, a.luna_version)
    except (ValueError, OSError) as error:
        p.error(str(error))
    a.output.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run([str(a.publisher.resolve()), 'pack', '--source', str(a.work_dir.resolve()),
                    '--profiles', str(a.profiles.resolve()), '--platform', a.platform,
                    '--output', str(a.output.resolve())], check=True)


if __name__ == '__main__':
    main()
