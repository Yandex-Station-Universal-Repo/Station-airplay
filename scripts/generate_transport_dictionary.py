# Only finite, tested wrappers are declared; never substring/keyword matching.
prefixes = {
    'Pause': ['', 'давай'],
    'Play': ['', 'давай'],
    'Next': ['', 'включи', 'поставь', 'переключи', 'давай', 'включи мне',
             'поставь мне', 'переключи на', 'перейди на'],
    'Previous': ['', 'включи', 'поставь', 'переключи', 'верни', 'давай',
                 'включи мне', 'поставь мне', 'переключи на', 'перейди на'],
    'Restart': ['', 'давай'],
}
phrases = {}
for command, bases in groups.items():
    for base in bases:
        for prefix in prefixes[command]:
            plain = f'{prefix} {base}'.strip()
            for phrase in [plain, f'пожалуйста {plain}', f'{plain} пожалуйста',
                           f'пожалуйста {plain} пожалуйста']:
                old = phrases.setdefault(phrase, command)
                assert old == command, (phrase, old, command)
assert len(phrases) <= 8192
assert all(len(p.encode()) <= 128 for p in phrases)
output = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / 'source/transport_dictionary.json'
output.write_text(
    json.dumps(phrases, ensure_ascii=False, indent=2, sort_keys=True) + '\n', encoding='utf-8')
print('dictionary phrases:', len(phrases))
